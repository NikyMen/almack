import { sqliteTable, integer, text, real } from "drizzle-orm/sqlite-core";
import { sql } from "drizzle-orm";
export const cajaTurnos = sqliteTable("caja_turnos", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  sucursalId: integer("sucursal_id").notNull(),
  cajaId: integer("caja_id").notNull(),
  responsable: text("responsable").notNull(),
  responsableUsuario: text("responsable_usuario").notNull().default(""),
  aperturaUsuario: text("apertura_usuario").notNull().default(""),
  aperturaEstado: text("apertura_estado").notNull().default("aprobada"),
  aperturaRevisadaPor: text("apertura_revisada_por"),
  aperturaRevisadaEn: integer("apertura_revisada_en", { mode: "timestamp" }),
  anulacionMotivo: text("anulacion_motivo"),
  fondoContado: real("fondo_contado"),
  detalleApertura: text("detalle_apertura").notNull().default("{}"),
  detalleCierre: text("detalle_cierre").notNull().default("{}"),
  declaradoCierre: real("declarado_cierre"),
  aprobadoPor: text("aprobado_por"),
  aprobadoEn: integer("aprobado_en", { mode: "timestamp" }),
  cerradoPor: text("cerrado_por"),
  fondoInicial: real("fondo_inicial").notNull(),
  fondoEsperado: real("fondo_esperado"),
  diferenciaApertura: real("diferencia_apertura"),
  motivoApertura: text("motivo_apertura").notNull().default(""),
  arqueoEn: integer("arqueo_en", { mode: "timestamp" }),
  estado: text("estado").notNull().default("abierta"),
  abiertoEn: integer("abierto_en", { mode: "timestamp" }).default(sql`(strftime('%s','now'))`),
  cerradoEn: integer("cerrado_en", { mode: "timestamp" }),
  efectivoEsperado: real("efectivo_esperado"),
  efectivoContado: real("efectivo_contado"),
  diferencia: real("diferencia"),
  resumen: text("resumen"),
  observaciones: text("observaciones").notNull().default(""),
});
export const cajaMovimientos = sqliteTable("caja_movimientos", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  turnoId: integer("turno_id").notNull().references(() => cajaTurnos.id),
  tipo: text("tipo").notNull(),
  monto: real("monto").notNull(),
  motivo: text("motivo").notNull(),
  responsable: text("responsable").notNull(),
  fecha: integer("fecha", { mode: "timestamp" }).default(sql`(strftime('%s','now'))`),
});
export const cajaSeguridad = sqliteTable("caja_seguridad", {
  id: integer("id").primaryKey(),
  claveHash: text("clave_hash").notNull(),
  actualizadoPor: text("actualizado_por").notNull(),
  actualizadoEn: integer("actualizado_en", { mode: "timestamp" }).notNull(),
});
export const cajaIntentos = sqliteTable("caja_intentos", {
  usuario: text("usuario").primaryKey(),
  fallos: integer("fallos").notNull().default(0),
  bloqueadoHasta: integer("bloqueado_hasta").notNull().default(0),
});
export const cajaExtracciones = sqliteTable("caja_extracciones", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  solicitudId: text("solicitud_id").notNull().unique(),
  sucursalId: integer("sucursal_id").notNull(),
  turnoId: integer("turno_id").notNull().references(() => cajaTurnos.id),
  estadoCaja: text("estado_caja").notNull(),
  monto: real("monto").notNull(),
  saldoRestante: real("saldo_restante"),
  motivo: text("motivo").notNull(),
  entregadoA: text("entregado_a").notNull().default(""),
  responsable: text("responsable").notNull(),
  fecha: integer("fecha", { mode: "timestamp" }).default(sql`(strftime('%s','now'))`),
});
export const cajaTraspasos = sqliteTable("caja_traspasos", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  turnoId: integer("turno_id").notNull().references(() => cajaTurnos.id),
  saliente: text("saliente").notNull(),
  salienteUsuario: text("saliente_usuario").notNull(),
  entrante: text("entrante"),
  entranteUsuario: text("entrante_usuario"),
  contadoSalida: real("contado_salida").notNull(),
  contadoEntrada: real("contado_entrada"),
  detalleSalida: text("detalle_salida").notNull().default("{}"),
  detalleEntrada: text("detalle_entrada"),
  esperado: real("esperado").notNull(),
  estado: text("estado").notNull().default("pendiente"),
  iniciadoEn: integer("iniciado_en", { mode: "timestamp" }).default(sql`(strftime('%s','now'))`),
  recibidoEn: integer("recibido_en", { mode: "timestamp" }),
  canceladoPor: text("cancelado_por"),
  canceladoEn: integer("cancelado_en", { mode: "timestamp" }),
  motivoCancelacion: text("motivo_cancelacion"),
});
export const cajaRevisiones = sqliteTable("caja_revisiones", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  turnoId: integer("turno_id").notNull().references(() => cajaTurnos.id),
  administrador: text("administrador").notNull(),
  contadoAnterior: real("contado_anterior").notNull(),
  contadoNuevo: real("contado_nuevo").notNull(),
  motivo: text("motivo").notNull(),
  tipo: text("tipo").notNull().default("cierre"),
  fecha: integer("fecha", { mode: "timestamp" }).default(sql`(strftime('%s','now'))`),
});
export const cajaSaldoMovimientos = sqliteTable("caja_saldo_movimientos", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  turnoId: integer("turno_id").notNull().references(() => cajaTurnos.id),
  tipo: text("tipo").notNull(),
  monto: real("monto").notNull(),
  motivo: text("motivo").notNull(),
  responsable: text("responsable").notNull(),
  fecha: integer("fecha", { mode: "timestamp" }).default(sql`(strftime('%s','now'))`),
});
